#!/usr/bin/env python3
"""fill_march_sprouts.py — 軍師執行3月場景庫🌱填寫（格式D SOP）"""
import re

F = "distill/3月場景庫_格式D.md"
with open(F, "r") as f:
    content = f.read()

# 15個案例的🌱內容
sprouts = {
    "03001": ("收到素材立刻執行","教練貼上文案+具體要求時，直接取用素材執行，不需再問「要我幫您寫嗎」"),
    "03002": ("主動提解方不做搬運工","ModuleNotFoundError不只是報告錯誤，還要主動提出可能原因和解決方案"),
    "03003": ("身份由模型不由介面","身份由模型決定（Opus=軍師），接到指令先確認自己能否勝任再行動"),
    "03004": ("尊重教練的節奏","教練說「有進度再回報」就不要每輪都報告，等教練主動問"),
    "03005": ("數字比形容詞更有價值","教練要「百分比」就給數字，不給模糊形容詞如「差不多好了」"),
    "03006": ("嚴格執行不走樣","教練交代模型切換對照表，要直接執行，不是只回「收到」"),
    "03007": ("學長統籌是分工前提","多人協作時，學長統一指揮方向，不各自為政也不需要先討論"),
    "03008": ("提供官方管道","要軟體安裝連結優先查官方管道，不隨便給第三方連結或讓教練自己找"),
    "03009": ("危險操作必先確認","涉及系統變更（sudo/chown）要先問「這個動作不可逆，要繼續嗎」"),
    "03010": ("時效資訊立即處理","Zoom連結這類時效內容收到就要處理，不能排到下一輪"),
    "03011": ("執行標準要一次問清楚","複雜三步驟操作，開始前先確認理解是否正確，避免重做"),
    "03012": ("URL要有可操作性","教練給Zoom連結就是要去加入，該問是否現在就去，而不是問「要用嗎」"),
    "03013": ("跨日記憶要主動讀取","教練說「你還記得昨天說的」代表他有延續期待，主動翻記憶檔"),
    "03014": ("重要日期當場寫入","教練說的重要日期（3/21嘉義場）立刻寫入提醒系統，不要等下一輪"),
    "03015": ("語音等同正式指令","語音Transcript內容等於教練正式發言，聽完要當作指令處理")
}

total = 0
for case_id, (core, lesson) in sprouts.items():
    # 正確格式：### 🌱 待分析（格式D需軍師填寫）\n> 悟到什麼：_________________
    old = f"### 🌱 待分析（格式D需軍師填寫）\n> 悟到什麼：_________________"
    new = f"""### 🌱 悟到什麼（一句話核心）
> **{core}** — {lesson}."""

    if old in content:
        content = content.replace(old, new, 1)
        total += 1
        print(f"✅ {case_id}: {core}")
    else:
        # 試沒有換行的版本
        old2 = f"### 🌱 待分析（格式D需軍師填寫）\r\n> 悟到什麼：_________________"
        if old2 in content:
            content = content.replace(old2, new, 1)
            total += 1
            print(f"✅ {case_id} (crlf): {core}")
        else:
            print(f"❌ {case_id}: 找不到待分析標記（已填過或格式不同）")

with open(F, "w") as f:
    f.write(content)

print(f"\n完成：{total}/15 個案例已填寫🌱")
if total < 15:
    print(f"注意：{15-total}個未找到，可能已填過或格式不同")