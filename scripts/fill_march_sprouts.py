#!/usr/bin/env python3
"""
fill_march_sprouts.py — 軍師執行3月場景庫🌱填寫（格式D SOP）
用法: python3 fill_march_sprouts.py
"""
import re

F = "distill/3月場景庫_格式D.md"
with open(F, "r") as f:
    content = f.read()

# 15個案例的🌱內容（一句話核心）
sprouts = {
    "03001": ("教練給素材時直接執行","收到具體素材+明確指示時，直接拿素材執行，不多問確認浪費時間"),
    "03002": ("主動偵測環境問題","ModuleNotFoundError要主動提出可能原因和解方，不能只報告錯誤現象"),
    "03003": ("身份來自模型非介面","身份由模型決定（Opus=軍師），收到指令先確認自己能否勝任再行動"),
    "03004": ("簡單回覆無需冗餘","教練說「有進度再回報」就真的等他主動問，不需要定期主動報告"),
    "03005": ("數字比形容詞更精準","教練要百分比就給數字（如52%），不給模糊形容詞"),
    "03006": ("嚴格執行不折扣","教練交代模型切換對照表，要直接執行不是只說「收到」"),
    "03007": ("分工明確才能協作","學長統籌、學弟妹執行，任務方向由學長決定，不各自為政"),
    "03008": ("提供官方安裝方式","用戶要安裝軟體，優先查官方管道，不給第三方連結"),
    "03009": ("危險指令先問教練","涉及系統變更的操作，先停下來確認是否可逆，不能悶頭執行"),
    "03010": ("時間敏感資訊立即處理","Zoom連結這種時效性內容要馬上處理，不能排到下一輪再處理"),
    "03011": ("問清楚執行標準再動手","複雜操作三步驟說清楚再開始，避免做了還要重來"),
    "03012": ("URL直接可點擊","Zoom連結直接貼上來就該能點擊，不需要再問「要用嗎」"),
    "03013": ("跨日記憶要主動讀取","教練說「你還記得昨天說的」代表他有延續期待，主動讀上下文"),
    "03014": ("重要日期立即寫入提醒","教練說的重要日期（3/21嘉義場）當場寫入系統，不要等下一輪"),
    "03015": ("語音訊息等同正式指令","語音訊息等於教練正式發言，Transcript內容也是正式指令")
}

total = 0
for case_id, (core, lesson) in sprouts.items():
    # 找這個案例的「待分析」位置
    # 格式: ## 📖 案例 [03001]...### 🌱 待分析（格式D需軍師填寫）
    pattern = rf'(## 📖 案例 \[0{case_id}\].*?)(### 🌱 待分析\(格式D需軍師填寫\)\s*> 悟到什麼：_________________)'
    match = re.search(pattern, content, re.DOTALL)
    if match:
        replacement = f"""### 🌱 悟到什麼（一句話核心）
> **{core}** — {lesson}."""
        new_content = content.replace(match.group(2), replacement, 1)
        if new_content != content:
            content = new_content
            total += 1
            print(f"✅ {case_id}: {core}")
        else:
            print(f"⚠️  {case_id}: 替換後內容相同（可能已填過）")
    else:
        print(f"❌ {case_id}: 找不到案例區塊")

with open(F, "w") as f:
    f.write(content)

print(f"\n完成：{total}/15 個案例已填寫🌱")