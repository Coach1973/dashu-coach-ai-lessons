#!/bin/bash
# Hook：UserPromptSubmit
# 用途：偵測教練下任務的訊號，自動注入「執行合約」到 context。
#       讓 AI 每次接到任務就知道「什麼叫完成」——不靠 AI 記得，靠系統強制注入。
# 設計：只在偵測到「任務關鍵詞」時注入，閒聊靜默，避免炸 token。
# 依據：特助場景庫117個場景 TOP5 痛點（說了不做26次、沒憑證16次等）
# 軍師建立 2026-05-28
set -uo pipefail

INPUT=$(cat)
PROMPT=$(printf '%s' "$INPUT" | /usr/bin/jq -r '.prompt // ""' 2>/dev/null)

[[ -z "$PROMPT" ]] && exit 0

# === 任務關鍵詞偵測 ===
# 命中任何一組 = 教練在下任務，注入執行合約
IS_TASK=0

# 主動指派類（幫我做X）
if printf '%s' "$PROMPT" | grep -qE "幫我|請你|幫忙|麻煩你"; then
  IS_TASK=1
fi

# 動作指令類（去做X）
if printf '%s' "$PROMPT" | grep -qE "你去|去讀|去寫|去建|去修|去查|去跑|去搜|去設|去確認|去測|去執行|去處理|去上傳|去部署|去更新|去刪"; then
  IS_TASK=1
fi

# 產出要求類（做一個X/建一個X）
if printf '%s' "$PROMPT" | grep -qE "做一個|建一個|寫一個|設一個|建立|新增|產生|輸出|生成"; then
  IS_TASK=1
fi

# 修改/檢查類
if printf '%s' "$PROMPT" | grep -qE "修改|更新|修正|修復|檢查|確認|驗證|測試一下|跑一下|執行一下"; then
  IS_TASK=1
fi

# 本場任務類（開工/繼續）
if printf '%s' "$PROMPT" | grep -qE "開始做|繼續做|繼續執行|把.*做完|把.*完成|完成.*任務"; then
  IS_TASK=1
fi

# 排除純閒聊/問答（避免誤觸）
# 如果 prompt 只是問問題，不注入
if printf '%s' "$PROMPT" | grep -qE "^你覺得|^你怎麼|^你認為|^什麼是|^解釋|^告訴我|^說說|^介紹"; then
  IS_TASK=0
fi

[[ "$IS_TASK" -eq 0 ]] && exit 0

# === 注入執行合約 ===
cat <<'GOAL'
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
🎯 執行合約（系統自動注入，任務啟動）
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

根據117個場景TOP5痛點，以下是本次任務的完成標準：

✅ 什麼叫「完成」（缺一不算）
  1. 任務實際執行完畢——不只是說「好的」「收到」
  2. 有具體憑證：commit hash / 檔案路徑 / 指令輸出結果
  3. 主動回報：做了什麼＋憑證在哪

⚡ 執行鐵律（對應最高頻失敗模式）
  • 方向清楚→直接執行，不問「要不要做」（#08，最高頻26次）
  • 先確認清楚再行動，不瞎猜（#09，21次）
  • 聽到陌生的詞、不是教練習慣的用語、或上下文接不上→第一句先問「請問您說的是『XXX』嗎？是不是語音輸入錯誤？」，教練確認前不查、不動手（#18／細則N3）
  • 自問自答驗證後再回答（#03，19次）
  • 解決問題，不只解釋原因（#04，16次）
  • 口頭說完成=零，要有憑證（#05，16次）

🚫 以下行為視為任務失敗
  • 說「完成了」但沒有任何憑證
  • 叫教練自己複製貼上任何東西
  • 遇到障礙只道歉，沒有提出解法
  • 找不到檔案就假裝找到
  • 承諾了沒做到

📋 Session 結束前必做
  更新 JUNSHI_HANDOFF_LATEST.md：做了什麼、commit hash、下一步
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
GOAL

exit 0
